// ============================================================
//  物語データ（ここを書き換えるだけで話を変えられます）
//
//  ■ ノードの種類
//   {k:'n', x:'地の文'}                 ... ナレーション
//   {k:'s', w:'名前', x:'セリフ'}        ... 会話
//   {k:'loc', x:'場所名'}               ... 場所ラベルと背景を変える（ホーム/教室/自宅/駅員室）
//   {k:'p', x:'...'}                    ... 相手(H)からのノートの文章
//   {k:'r', parts:[...]}                ... 自分の返事（下で説明）
//   {k:'if', c:s=>条件, t:[...], f:[...]} ... 条件で場面を分ける（t=成立 / f=不成立、fは省略可）
//   {k:'do', e:s=>{...}}                ... 状態を書き換えるだけ（フラグを立てる等）
//   {k:'menu', x, o:[...]}              ... 誰に話を聞くか選ぶ（選択肢に if も使える）
//   {k:'guess', x, o:[...]}             ... 正体を当てる
//
//  ■ 返事 {k:'r', parts:[...]} の書き方
//   parts には「文字列」と「空欄 {id, o:[選択肢]}」を並べます。
//     ['はじめまして。\n', {id:'tone', o:[...]}, '\nまたね。']
//        → 「はじめまして。」が書かれてから、選択肢が出る（途中まで書いてから選ぶ）
//     [{id:'told', o:[...]}, '\nそれより…']
//        → 最初から選択肢が出る（いきなり選ぶ）
//     空欄は何個でも並べられる（選ぶたびに続きが書かれていく）。
//   選択肢 {v:'warm', l:'表示される文', e:s=>{...}, if:s=>条件}
//     v … この選択を区別する名前（あとで s.a.質問ID === 'warm' のように使う）
//     l … ノートに書かれる文（関数にして過去の返事を混ぜることもできる）
//     e … 選んだときに実行する処理（省略可。例: s.trust++）
//     if … 条件を満たすときだけ、この選択肢を出す（省略可）
//   文字列部分も s=>... の関数にでき、過去の返事で文章を変えられる。
//
//  ■ 過去の返事の使い方（x や l、c、if に書く関数の中で使える。s は状態）
//   s.a.質問ID     ... そのとき選んだ選択肢の v        例: s.a.tone === 'warm'
//   s.said.質問ID  ... そのとき書いた文章そのもの      例: `「${s.said.worry}」と書いてくれたね`
//   s.f.名前       ... 自由なフラグ                     例: e:s=>{ s.f.metCat = true }
//   s.trust        ... 信頼度の数値
//   例）x: s => (s.a.tone==='warm' && s.a.advice==='talk') ? 'AとBの両方を選んだ人だけ読める文' : '別の文'
//   ※ まだ選んでいない質問の s.a.○○ は undefined になる。
//
//  ■ 演出ノード（画像・音・間）
//   {k:'bg', x:'ekisha_sit', fx:'shake'}  ... 背景を変える（bg/ の svg 名）。fx:'shake' で画面が揺れる
//   {k:'sfx', t:'ざっ、ざっ', snd:'steps'}  ... 擬音を画面に出し、音も鳴らす。snd は 'steps'（足音）/'chime'（チャイム）。count=足音の回数
//   {k:'wait', t:3000}                   ... 3秒間、絵だけを見せる（クリックで飛ばせる）
//   {k:'fade', t:3000}                   ... 3秒かけてゆっくり暗転
//   {k:'n', x:'…', cover:'表紙の文字'}    ... ノートの表紙を見せながら地の文を出す
//   {k:'p', x:'…', by:'見出し'}           ... 相手のノート。by でノート上部の見出しを変えられる
//   {k:'ending', title:'DAY1　おわり', x:'つづく'} ... 終了画面
//   章の設定: { title:'章の題', bg:'dusk', img:'最初の背景', nodes:[…] }
// ============================================================

// ============================================================

